pub const CELL_W: u32 = 6;
pub const CELL_H: u32 = 8;
pub const COLS: u32 = 16;
pub const ROWS: u32 = 5;
pub const ATLAS_W: u32 = CELL_W * COLS;
pub const ATLAS_H: u32 = CELL_H * ROWS;

/// R8 atlas: 64 glyphs followed by a fully solid block used for flat UI quads.
pub fn build_atlas() -> Vec<u8> {
    let mut px = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
    for (i, g) in GLYPHS.iter().enumerate() {
        let (cx, cy) = (i as u32 % COLS, i as u32 / COLS);
        for (col, bits) in g.iter().enumerate() {
            for row in 0..7u32 {
                if bits & (1 << row) != 0 {
                    px[((cy * CELL_H + row) * ATLAS_W + cx * CELL_W + col as u32) as usize] = 255;
                }
            }
        }
    }
    for y in 0..CELL_H {
        for x in 0..CELL_W {
            px[((4 * CELL_H + y) * ATLAS_W + x) as usize] = 255;
        }
    }
    px
}

pub fn solid_uv() -> [f32; 2] {
    [(CELL_W as f32 * 0.5) / ATLAS_W as f32, (4.0 * CELL_H as f32 + CELL_H as f32 * 0.5) / ATLAS_H as f32]
}

pub fn glyph_uv(c: char) -> ([f32; 2], [f32; 2]) {
    let mut code = c.to_ascii_uppercase() as u32;
    if !(0x20..0x60).contains(&code) {
        code = b'?' as u32;
    }
    let i = code - 0x20;
    let (cx, cy) = (i % COLS, i / COLS);
    let u0 = (cx * CELL_W) as f32 / ATLAS_W as f32;
    let v0 = (cy * CELL_H) as f32 / ATLAS_H as f32;
    (
        [u0, v0],
        [u0 + (CELL_W - 1) as f32 / ATLAS_W as f32, v0 + (CELL_H - 1) as f32 / ATLAS_H as f32],
    )
}
